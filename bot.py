def get_question_keyboard(q_index, context):
    current_questions = context.user_data.get("current_questions", QUESTIONS)
    question = current_questions[q_index]
    keyboard = []
    for i, (answer_text, _) in enumerate(question["answers"]):
        keyboard.append([InlineKeyboardButton(answer_text, callback_data=f"answer:{q_index}:{i}")])
    return InlineKeyboardMarkup(keyboard)

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    context.user_data["q_index"] = 0
    context.user_data["scores"] = defaultdict(int)

    final_question = QUESTIONS[-1]
    pool = QUESTIONS[:-1]

    selected = random.sample(pool, k=min(QUESTIONS_PER_RUN - 1, len(pool)))
    selected.append(final_question)

    context.user_data["current_questions"] = selected

    intro = """🌌 Тест-приключение: какая фракция Twilight Imperium тебе подходит?

Каждый проход немного отличается.
Отвечай быстро — первый импульс честнее расчёта.

Начинаем."""

    await update.message.reply_text(intro)
    await ask_question(update, context)

async def ask_question(update: Update, context: ContextTypes.DEFAULT_TYPE):
    q_index = context.user_data.get("q_index", 0)
    current_questions = context.user_data.get("current_questions", QUESTIONS)

    if q_index >= len(current_questions):
        scores = context.user_data.get("scores", defaultdict(int))
        result = calculate_result(scores)
        await update.effective_chat.send_message(format_result(result, scores))
        return

    question = current_questions[q_index]

    message_text = (
        f"Вопрос {q_index + 1}/{len(current_questions)}\n\n"
        f"{question['text']}"
    )

    await update.effective_chat.send_message(
        message_text,
        reply_markup=get_question_keyboard(q_index, context),
    )

async def handle_answer(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    _, q_index_str, answer_index_str = query.data.split(":")
    q_index = int(q_index_str)
    answer_index = int(answer_index_str)

    current_q = context.user_data.get("q_index", 0)
    current_questions = context.user_data.get("current_questions", QUESTIONS)

    if q_index != current_q:
        await query.edit_message_text("Этот вопрос уже неактуален. Нажми /start, если хочешь начать заново.")
        return

    answer_text, tags = current_questions[q_index]["answers"][answer_index]

    scores = context.user_data.get("scores")
    if scores is None:
        scores = defaultdict(int)
        context.user_data["scores"] = scores

    for tag, value in tags.items():
        scores[tag] += value

    await query.edit_message_text(
        f"Вопрос {q_index + 1}/{len(current_questions)}\n\n"
        f"Твой выбор:\n{answer_text}"
    )

    context.user_data["q_index"] = q_index + 1
    await ask_question(update, context)

async def help_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        "Команды:\n"
        "/start — начать тест заново\n"
        "/help — помощь\n\n"
        "Бот задаёт жёсткие RPG/sci-fi/fantasy ситуации и подбирает фракцию из TI4 + PoK."
    )

def main():
    if not BOT_TOKEN:
        raise RuntimeError("Не найден BOT_TOKEN. Укажи токен в переменной окружения BOT_TOKEN.")

    app = ApplicationBuilder().token(BOT_TOKEN).build()
    app.add_handler(CommandHandler("start", start))
    app.add_handler(CommandHandler("help", help_command))
    app.add_handler(CallbackQueryHandler(handle_answer, pattern=r"^answer:"))

    print("Бот запущен. Нажми Ctrl+C для остановки.")
    app.run_polling()

if __name__ == "__main__":
    main()
