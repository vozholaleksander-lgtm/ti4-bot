def ending_matches(scores, ending):
    return all(scores[k] >= v for k, v in ending["need"].items())

def calculate_result(scores):
    for ending in SECRET_ENDINGS:
        if ending_matches(scores, ending):
            return {"secret": True, "title": ending["title"], "text": ending["text"], "factions": ending["factions"]}
    faction_scores = []
    for faction, data in FACTIONS.items():
        total = sum(scores[tag] * weight for tag, weight in data["tags"].items())
        faction_scores.append((total, faction))
